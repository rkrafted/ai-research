#!/usr/bin/env python3
"""Build docs/upgrades.md: the R5 shortlist, joined to a deterministic KB query.

    python3 tools/upgrades/shortlist.py            # writes docs/upgrades.md
    python3 tools/upgrades/shortlist.py --check    # builds in memory, diffs

The candidate list lives in tools/upgrades/candidates.py. For every candidate
the builder queries data/kb.sqlite (R2) for a grounding video claim (with its
[MM:SS] timestamp) and an arXiv paper, so each source in the doc is reproducible
from the KB. When the KB has no match the curated fallback source is used.
"""
from __future__ import annotations

import argparse
import sqlite3
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from candidates import CANDIDATES  # noqa: E402

REPO = Path(__file__).resolve().parents[2]
KB = REPO / "data" / "kb.sqlite"
OUT = REPO / "docs" / "upgrades.md"

# the eight trials queued this session (gpu_jobs/upg-<name>.job.yaml)
QUEUED = ["kv-cache-quant", "flash-attention", "context-length", "parallel-batch",
          "speculative-draft", "qlora-grad-checkpoint", "qlora-packing",
          "extraction-json-schema"]


def _like(term: str) -> str:
    return f"%{term.lower()}%"


def _claim_source(cur: sqlite3.Cursor, terms: list[str]):
    """Top-viewed video with a timestamped claim matching any term."""
    for term in terms:
        row = cur.execute(
            """select v.title, v.url, cl.timestamp, cl.claim
                 from claims cl join videos v on v.id = cl.video_id
                where lower(cl.claim) like ?
                  and cl.timestamp is not null and cl.timestamp != ''
                order by (case when lower(v.title) like ? then 0 else 1 end),
                         v.views desc limit 1""", (_like(term), _like(term))).fetchone()
        if row:
            title, url, ts, claim = row
            stamp = ts if ts.startswith("[") else f"[{ts}]"
            return f'KB video "{title}" {stamp} {url} — "{claim[:90]}"'
    return None


def _paper_source(cur: sqlite3.Cursor, terms: list[str]):
    for term in terms:
        row = cur.execute(
            """select arxiv_id, title from papers
                where lower(title) like ? order by length(title) asc limit 1""",
            (_like(term),)).fetchone()
        if row:
            return f"arXiv {row[0]} {row[1]}"
    return None


def kb_source(cur: sqlite3.Cursor, cand: dict) -> str:
    parts = []
    claim = _claim_source(cur, cand.get("kb_claim_terms", []))
    paper = _paper_source(cur, cand.get("kb_arxiv_terms", []))
    if claim:
        parts.append(claim)
    if paper:
        parts.append(paper)
    if not parts:
        return cand.get("fallback_source", "no KB source")
    return " + ".join(parts)


def render(cur: sqlite3.Cursor) -> str:
    lines = [
        "# R5 — candidate upgrades for our local setup (3090 24 GB, 30 GB RAM, Ollama, QLoRA)",
        "",
        "Generated by `python3 tools/upgrades/shortlist.py` from `tools/upgrades/candidates.py`",
        "joined to a deterministic query over `data/kb.sqlite` (R2) and the R4 verified results",
        "(`docs/results.md`). One line per candidate: source · expected gain · cost to try · risk ·",
        "how. Only a runner GPU job writes `state/upgrades/<name>.json`; a session never does.",
        "",
        f"Trials queued this session ({len(QUEUED)}): " + ", ".join(f"`{q}`" for q in QUEUED) + ".",
        "Each is <= 30 GPU-minutes and <= 1.5 GB of downloads (the MoE offload entry is the one",
        "gated download, 16 GB, and is not queued).",
        "",
        "Source legend: `KB video` = the top-viewed video with a timestamped claim matching the",
        "technique in the R2 knowledge base; `arXiv` = a paper whose title matches, from R2.",
        "",
    ]
    areas = ["inference-speed", "fit-bigger", "fine-tune-efficiency", "data-tools"]
    for area in areas:
        lines.append(f"## {area}")
        lines.append("")
        for c in CANDIDATES:
            if c["area"] != area:
                continue
            src = kb_source(cur, c)
            queued = " · **queued**" if c["id"] in QUEUED else ""
            lines.append(
                f"- **{c['id']}** · {c['title']} · source: {src} · expected: {c['expected']} · "
                f"cost: {c['cost_min']} GPU-min, {c['download_gb']} GB · risk: {c['risk']} · "
                f"how: `{c['how']}`{queued}")
        lines.append("")
    lines.append("## Trial protocol")
    lines.append("")
    lines.append("- `inference-speed` / `fit-bigger` run on the cached 27B `qwen3.8-27b-uncensored:latest`")
    lines.append("  GGUF through Ollama's bundled `llama-server`, 50 real R2 ingest prompts, greedy.")
    lines.append("- `fine-tune-efficiency` runs a 6-step NF4 QLoRA loop on the cached 9B base")
    lines.append("  `empero-ai/Qwen3.8-9B-Distill` and reports step time and `torch.cuda.max_memory_allocated`.")
    lines.append("- `data-tools` runs the 9B on the hard sales-brain transcript extraction task")
    lines.append("  (7 deal fields) and reports field-F1, schema validity and latency.")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="do not write; fail if docs differ")
    a = ap.parse_args()
    con = sqlite3.connect(KB)
    try:
        text = render(con.cursor())
    finally:
        con.close()
    if a.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if cur != text:
            print("docs/upgrades.md is stale; rerun tools/upgrades/shortlist.py", file=sys.stderr)
            return 1
        print("docs/upgrades.md is up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

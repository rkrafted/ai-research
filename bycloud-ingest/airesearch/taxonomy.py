"""Visible technique taxonomy behind the R3 lens score.

The PLAN sec 2 axes (capability per parameter, per FLOP/VRAM, test-time
compute, data efficiency, cost to try, transfer) are judgements about a
*technique*, not about how often a transcript happens to say a word. Encoding
them here, once, as integers 0..100 makes the whole score auditable: a reviewer
can change one number and re-run ``python -m airesearch.lens build``.

Evidence quality is NOT here — it is counted from ``data/kb.sqlite`` (papers,
repos, numeric claims, channel diversity). The rank is therefore
``taxonomy profile x KB evidence``, fully deterministic and LLM-free at scoring
time.

``FAMILY`` folds noisy surface forms ("4-bit quantization", "GPTQ", "QAT")
onto one family so the digest lists a technique once.

Fields per family:
  param  capability per parameter: does it make a fixed-size model smarter?
  flop   capability per FLOP / per VRAM: does it run or train on 24 GB?
  ttc    test-time compute: can we trade 3090 time for quality?
  data   data efficiency: fewer / cheaper examples for the same gain?
  cost   estimated 3090 GPU-hours for one small reproduction (>= 0.25)
  theme  digest group heading
  why    one-line "why it helps limited compute"
  areas  which of our projects it transfers to (distill, extraction, agents,
         speech, vision, eval, training)
"""

